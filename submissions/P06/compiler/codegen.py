from compiler.ast_nodes import Number, Unary, Binary

def generate_python(node):
    def emit(current):
        if isinstance(current, Number):
            value = int(current.value) if current.value.is_integer() else current.value
            return repr(value)
        if isinstance(current, Unary):
            return f"(-{emit(current.operand)})"
        if isinstance(current, Binary):
            return f"({emit(current.left)} {current.operator} {emit(current.right)})"
        raise TypeError(f"Unsupported AST node: {type(current).__name__}")

    return "# Generated by Attribute Grammar Evaluator\n" \
           f"result = {emit(node)}\n" \
           "print(result)\n"
