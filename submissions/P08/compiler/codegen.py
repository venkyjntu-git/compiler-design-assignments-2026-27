"""Python code generation from the loop-nest IR."""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from compiler.ir import IRProgram, LoopNest, access_to_str, expr_to_str


@dataclass
class CompiledProgram:
    """Everything produced by compile_program()."""
    source_name: str
    code: str
    ir: IRProgram
    input_shapes: dict
    output_shapes: dict
    optimized: bool
    ast: Any = None
    ir_unoptimized: Any = None
    generated_path: Any = None

    @property
    def applied(self) -> list:
        return self.ir.applied

    @property
    def not_applied(self) -> list:
        return self.ir.not_applied


def _alloc(shape) -> str:
    if len(shape) == 1:
        return f"[0] * {shape[0]}"
    return f"[{_alloc(shape[1:])} for _ in range({shape[0]})]"


def _range(loop) -> str:
    if loop.step != 1:
        return f"range({loop.lower}, {loop.upper}, {loop.step})"
    if loop.lower == 0:
        return f"range({loop.upper})"
    return f"range({loop.lower}, {loop.upper})"


def _emit_nest(lines: list, nest: LoopNest, number: int):
    lines.append(f"    # --- loop nest {number}" +
                 (f" (tile size {nest.tile_size})" if nest.tile_size else ""))
    for stmt in nest.body:
        lines.append(f"    # {stmt.source}")
    depth = 1
    for loop in nest.loops:
        lines.append("    " * depth + f"for {loop.var} in {_range(loop)}:")
        depth += 1
    for stmt in nest.body:
        op = "+=" if stmt.accumulate else "="
        lines.append("    " * depth + f"{access_to_str(stmt.target, stmt.indices, True)} {op} "
                     f"{expr_to_str(stmt.expr, True)}")


def generate_code(program: IRProgram, source_name: str, optimized: bool) -> str:
    L = ["# Generated by TensorDSLCompiler - do not edit by hand.",
         f"# Source DSL file: {source_name}",
         f"# Optimization passes: {'enabled' if optimized else 'disabled'}"]
    if program.applied:
        L.append("# Optimizations applied:")
        L += [f"#   - {m}" for m in program.applied]
    else:
        L.append("# Optimizations applied: none")
    if program.not_applied:
        L.append("# Optimizations not applied:")
        L += [f"#   - {m}" for m in program.not_applied]
    L += ["", f"INPUT_SHAPES = {{{', '.join(f'{n!r}: {s!r}' for n, s in program.input_shapes().items())}}}",
          "", "", "def run(inputs):"]
    for name in program.input_shapes():
        L.append(f"    {name} = inputs[{name!r}]")
    for t in program.tensors.values():
        if t.role != "input":
            L.append(f"    {t.name} = {_alloc(t.shape)}")
    for n, nest in enumerate(program.nests):
        L.append("")
        _emit_nest(L, nest, n)
    outs = ", ".join(f"{n!r}: {n}" for n in program.output_shapes())
    L += ["", f"    return {{{outs}}}", "", "",
          "def _sample_inputs():",
          "    counter = [1]",
          "",
          "    def fill(shape):",
          "        if len(shape) == 1:",
          "            start = counter[0]",
          "            counter[0] += shape[0]",
          "            return list(range(start, start + shape[0]))",
          "        return [fill(shape[1:]) for _ in range(shape[0])]",
          "",
          "    return {name: fill(shape) for name, shape in INPUT_SHAPES.items()}",
          "", "",
          'if __name__ == "__main__":',
          "    for _name, _value in run(_sample_inputs()).items():",
          '        print(_name, "=", _value)',
          ""]
    return "\n".join(L)


def save_code(code: str, output_dir, stem: str) -> Path:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    safe = re.sub(r"[^A-Za-z0-9_]+", "_", stem).strip("_") or "program"
    path = out / f"{safe}.py"
    path.write_text(code, encoding="utf-8", newline="\n")
    return path
