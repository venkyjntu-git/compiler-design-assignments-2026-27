# Case 1: Sequential assignments
def test_case_1_sequential_assignments():
    code = "a = 10;\nb = 20;\nc = a + b;\nd = c * 2;"
    cfg = compile_c_to_cfg(code)
    block_ids = [b.id for b in cfg.blocks]
    assert block_ids == ["ENTRY", "B1", "EXIT"]
    assert len(cfg.edges) == 2
    edge_types = [e.type for e in cfg.edges]
    assert edge_types == ["fallthrough", "fallthrough"]
    
    rd = ReachingDefinitions(cfg).run()
    assert rd["total_iterations"] >= 1
    # B1 produces 6 definitions: d1..d6
    assert len(rd["final_out"]["B1"]) == 6

# Case 2: Multiple definitions of the same variable (KILL verification)
def test_case_2_multiple_definitions_kill():
    code = "x = 1;\nx = 2;\nx = 3;"
    cfg = compile_c_to_cfg(code)
    rd = ReachingDefinitions(cfg).run()
    # d1 and d2 define x, but d3 is the final definition of x in B1
    # Only d3 reaches the end of B1 for x
    out_b1 = rd["final_out"]["B1"]
    assert "d3" in out_b1
    assert "d1" not in out_b1
    assert "d2" not in out_b1

# Case 3: If-else statement with a merge point
def test_case_3_if_else_merge():
    code = """
    x = 10;
    if (x > 5) {
        y = 1;
    } else {
        y = 2;
    }
    z = y + 1;
    """
    cfg = compile_c_to_cfg(code)
    block_ids = [b.id for b in cfg.blocks]
    assert len(block_ids) == 6  # ENTRY, B1 (condition), B2 (else), B3 (then), B4 (join), EXIT
    edge_types = {e.type for e in cfg.edges}
    assert "conditional_true" in edge_types
    assert "conditional_false" in edge_types

    # In Reaching Definitions, at the merge block (B4), both then and else defs of y reach
    rd = ReachingDefinitions(cfg).run()
    in_b4 = rd["final_in"]["B4"]
    def_map = {d["id"]: d for d in rd["definitions_table"]}
    # Definitions of y from both branches reach IN[B4]
    y_defs_in_b4 = [d_id for d_id in in_b4 if def_map[d_id]["var"] == "y"]
    assert len(y_defs_in_b4) == 2

# Case 4: While loop with a back edge
def test_case_4_while_loop_back_edge():
    code = """
    i = 0;
    while (i < 5) {
        i = i + 1;
    }
    """
    cfg = compile_c_to_cfg(code)
    back_edges = [e for e in cfg.edges if e.type == "back_edge"]
    assert len(back_edges) == 1
    assert back_edges[0].label == "Loop Back"

    # Fixed point must take at least 2 iterations due to cyclic data flow
    rd = ReachingDefinitions(cfg).run()
    assert rd["total_iterations"] >= 2
    lv = LiveVariables(cfg).run()
    assert lv["total_iterations"] >= 2

# Case 5: Nested conditional statements
def test_case_5_nested_conditions():
    code = """
    x = 10;
    y = 0;
    if (x > 0) {
        if (x > 5) {
            y = 1;
        } else {
            y = 2;
        }
    } else {
        y = 3;
    }
    result = y;
    """
    cfg = compile_c_to_cfg(code)
    # Check that multiple branch points exist
    branch_edges = [e for e in cfg.edges if e.type in ("conditional_true", "conditional_false")]
    assert len(branch_edges) == 4  # 2 branches * 2 targets each
    rd = ReachingDefinitions(cfg).run()
    assert rd["total_iterations"] >= 1

# Case 6: Combined branching and loops
def test_case_6_combined_branch_and_loop():
    code = """
    i = 1;
    sum = 0;
    while (i <= 5) {
        if (i % 2 == 0) {
            sum = sum + i;
        } else {
            sum = sum + 1;
        }
        i = i + 1;
    }
    """
    cfg = compile_c_to_cfg(code)
    back_edges = [e for e in cfg.edges if e.type == "back_edge"]
    assert len(back_edges) >= 1
    true_edges = [e for e in cfg.edges if e.type == "conditional_true"]
    assert len(true_edges) >= 2  # loop condition + if condition

    rd = ReachingDefinitions(cfg).run()
    assert rd["total_iterations"] >= 3

# Case 7: Expression invalidation in Available Expressions
def test_case_7_expression_invalidation():
    code = """
    x = 1;
    y = 2;
    a = x + y;
    x = 10;
    b = x + y;
    """
    cfg = compile_c_to_cfg(code)
    ae = AvailableExpressions(cfg).run()
    # At B1, 'x + y' was computed, but then x was re-assigned to 10.
    # Therefore, the earlier 'x + y' was killed and re-generated by the second calculation.
    assert "x + y" in ae["universal_set"]
    assert "x + y" in ae["block_kill"]["B1"]

