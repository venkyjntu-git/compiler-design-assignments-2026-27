# Case 11: Completely new user-written program
def test_case_11_new_user_program():
    code = """
    total = 0;
    count = 4;
    while (count > 0) {
        step = count * 2;
        total = total + step;
        count = count - 1;
    }
    final_ans = total;
    """
    res = client.post("/api/analyze/all", json={"code": code})
    assert res.status_code == 200
    data = res.json()
    cfg = data["cfg"]
    assert len(cfg["blocks"]) >= 5
    assert any(e["type"] == "back_edge" for e in cfg["edges"])
    assert data["reaching_definitions"]["total_iterations"] >= 2
    assert data["live_variables"]["total_iterations"] >= 2
    assert len(data["available_expressions"]["final_in"]) > 0
